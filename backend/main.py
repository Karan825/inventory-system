# --- ORDERS ---
@app.post("/orders", response_model=schemas.Order, status_code=status.HTTP_201_CREATED)
def create_order(order: schemas.OrderCreate, db: Session = Depends(get_db)):
    # 1. Verify customer
    customer = db.query(models.Customer).filter(models.Customer.id == order.customer_id).first()
    if not customer:
        raise HTTPException(status_code=404, detail="Customer not found")

    total_amount = 0.0
    order_items_to_create = []

    # 2. Verify products and stock, calculate total
    for item in order.items:
        product = db.query(models.Product).filter(models.Product.id == item.product_id).first()
        if not product:
            raise HTTPException(status_code=404, detail=f"Product ID {item.product_id} not found")
        if product.stock_quantity < item.quantity:
            raise HTTPException(
                status_code=400, 
                detail=f"Insufficient stock for product {product.name}. Requested: {item.quantity}, Available: {product.stock_quantity}"
            )
        
        # Deduct stock
        product.stock_quantity -= item.quantity
        
        # Calculate amount
        total_amount += product.price * item.quantity
        
        # Prepare order item
        order_items_to_create.append(
            models.OrderItem(
                product_id=product.id,
                quantity=item.quantity,
                price_at_time_of_order=product.price
            )
        )

    # 3. Create Order
    db_order = models.Order(
        customer_id=order.customer_id,
        total_amount=total_amount,
    )
    db.add(db_order)
    db.flush() # To get the order ID

    # 4. Add items
    for oi in order_items_to_create:
        oi.order_id = db_order.id
        db.add(oi)

    db.commit()
    db.refresh(db_order)
    return db_order

